"""Generate src/data/airQuality/presets.ts from extracted PM2.5 fine series."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
source = json.loads((ROOT / "data/processed/presets/presets.json").read_text())
points = {p["id"]: p for p in source["points"]}
meta = source["metadata"]
rows = []
for key, point in points.items():
    if key == "cairo":
        continue
    rows.append({
        "id": key, "label": point["name"], "latitude": point["lat"], "longitude": point["lon"],
        "metadata": meta, "values": point["values"], "flags": point["flags"],
    })
text = "// Generated by tools/data/bundle_presets.py; never filled or interpolated.\n"
text += "/* eslint-disable no-loss-of-precision */\n"
text += "export const pm25PresetsData = " + json.dumps(rows, indent=2, ensure_ascii=False) + " as const\n"
out = ROOT / "src/data/airQuality/presets.ts"
out.write_text(text)
print("wrote", out, out.stat().st_size, "bytes")
for row in rows:
    print(row["id"], len(row["values"]), "nulls", sum(v is None for v in row["values"]))
